"""SFX and music libraries.

Sources, in priority order:
1. user files in assets/sfx and assets/music listed in their license_manifest.yaml (or simply dropped
   in: tags are guessed from folder and file names, and the manifest records the license);
2. the built-in library generated by storyforge.audio.synth into $DATA/library (CC0, created on
   first use; `storyforge assets` regenerates it).
"""

from __future__ import annotations

import re
from functools import lru_cache
from pathlib import Path

from storyforge.audio import dsp
from storyforge.config import ASSETS_DIR, get_settings
from storyforge.util.io import read_json, read_yaml, write_json

AUDIO_EXT = {".wav", ".flac", ".ogg", ".mp3", ".aiff", ".aif"}
LIB_VERSION = 3


def library_dir() -> Path:
    return get_settings().data_dir / "library"


def _guess_tags(path: Path, root: Path) -> list[str]:
    parts = [p.lower() for p in path.relative_to(root).with_suffix("").parts]
    words = set()
    for p in parts:
        words |= {w for w in re.split(r"[^a-z0-9]+", p) if w and not w.isdigit()}
    return sorted(words)


def _user_entries(kind: str) -> list[dict]:
    root = ASSETS_DIR / kind
    if not root.is_dir():
        return []
    manifest = read_yaml(root / "license_manifest.yaml", {}) or {}
    listed = {e["file"]: e for e in (manifest.get("sounds") or manifest.get("tracks") or []) if isinstance(e, dict)
              and e.get("file")}
    out = []
    for p in sorted(root.rglob("*")):
        if p.suffix.lower() not in AUDIO_EXT or not p.is_file():
            continue
        rel = p.relative_to(root).as_posix()
        e = listed.get(rel) or listed.get(p.name) or {}
        if str(e.get("enabled", True)).lower() in ("false", "0", "no"):
            continue
        tags = list(e.get("tags") or []) or _guess_tags(p, root)
        out.append({"file": str(p), "tags": tags, "moods": list(e.get("moods") or e.get("tags") or tags),
                    "license": e.get("license", "unknown - add it to license_manifest.yaml"),
                    "source": e.get("source", "user"), "bpm": e.get("bpm"), "loop": bool(e.get("loop", True)),
                    "user": True})
    return out


def ensure_library(force: bool = False, log=print) -> dict[str, list[dict]]:
    """Generate the built-in library if missing (or outdated) and return the merged index."""
    from storyforge.audio import synth

    lib = library_dir()
    meta_path = lib / "index.json"
    meta = read_json(meta_path, None)
    if force or not meta or meta.get("version") != LIB_VERSION:
        (lib / "sfx").mkdir(parents=True, exist_ok=True)
        (lib / "music").mkdir(parents=True, exist_ok=True)
        sfx = []
        for stem, (fn, tags) in synth.GENERATORS.items():
            p = lib / "sfx" / f"{stem}.wav"
            if force or not p.is_file():
                dsp.save(p, fn(), synth.SR, subtype="PCM_16")
            sfx.append({"file": str(p), "tags": sorted(set(tags + [stem])), "license": "CC0 (generated by StoryForge)",
                        "source": "storyforge.audio.synth", "user": False})
        music = []
        for mood in synth.MOODS:
            p = lib / "music" / f"{mood}.wav"
            if force or not p.is_file():
                log(f"generating music bed: {mood}")
                bed = synth.music_bed(mood, bars=16)
                dsp.save(p, synth.stereoize(bed), synth.SR, subtype="PCM_16")
            music.append({"file": str(p), "moods": [mood], "tags": [mood], "bpm": synth.MOODS[mood][0], "loop": True,
                          "license": "CC0 (generated by StoryForge)", "source": "storyforge.audio.synth", "user": False})
        meta = {"version": LIB_VERSION, "sfx": sfx, "music": music}
        write_json(meta_path, meta)
        index.cache_clear()
    return {"sfx": _user_entries("sfx") + meta["sfx"], "music": _user_entries("music") + meta["music"]}


@lru_cache(maxsize=1)
def index() -> dict[str, list[dict]]:
    return ensure_library()


def find_sfx(tag: str, seed: int = 0) -> dict | None:
    """User sounds win; among matches pick a variant deterministically (seed) for natural repetition."""
    idx = index()["sfx"]
    want = set(tag.lower().split("+"))
    for pool in ([e for e in idx if e.get("user")], [e for e in idx if not e.get("user")]):
        cands = [e for e in pool if want <= {t.lower() for t in e["tags"]}]
        if cands:
            return cands[seed % len(cands)]
    return None


def find_music(mood: str) -> dict | None:
    idx = index()["music"]
    for pool in ([e for e in idx if e.get("user")], [e for e in idx if not e.get("user")]):
        for e in pool:
            if mood in [m.lower() for m in e.get("moods", [])]:
                return e
    return next((e for e in idx if not e.get("user")), None)


@lru_cache(maxsize=256)
def load(path: str, stereo: bool = False):
    audio = dsp.load(path, dsp.SR, mono=not stereo)
    return audio
